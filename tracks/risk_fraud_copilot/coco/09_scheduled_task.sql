USE SCHEMA RISK_FRAUD_COPILOT.CORE;

-- Idempotent detector procedure: re-runs the corrected STRUCTURING_SQL from
-- 04_orchestration.py (the same window-function fix documented in
-- coco/README.md's "Live Pilot Results" section) and inserts a new FINDINGS
-- row only for an account not already carrying a structuring finding.
CREATE OR REPLACE PROCEDURE DETECT_AND_FILE_STRUCTURING()
RETURNS STRING
LANGUAGE SQL
AS
$$
DECLARE
    new_findings_count INT DEFAULT 0;
BEGIN
    CREATE OR REPLACE TEMPORARY TABLE TMP_CANDIDATES AS
    WITH deposits AS (
        SELECT txn_id, account_id, customer_id, txn_timestamp, amount
        FROM TRANSACTIONS
        WHERE type = 'cash_deposit' AND amount BETWEEN 8000 AND 9999.99
    ),
    windowed AS (
        SELECT *,
               COUNT(*) OVER (
                   PARTITION BY account_id ORDER BY txn_timestamp
                   RANGE BETWEEN CURRENT ROW AND INTERVAL '5 days' FOLLOWING
               ) AS window_count,
               ARRAY_AGG(txn_id) OVER (
                   PARTITION BY account_id ORDER BY txn_timestamp
                   RANGE BETWEEN CURRENT ROW AND INTERVAL '5 days' FOLLOWING
               ) AS window_txn_ids,
               SUM(amount) OVER (
                   PARTITION BY account_id ORDER BY txn_timestamp
                   RANGE BETWEEN CURRENT ROW AND INTERVAL '5 days' FOLLOWING
               ) AS window_total
        FROM deposits
    ),
    best_per_account AS (
        SELECT account_id, customer_id,
               window_txn_ids AS evidence_txn_ids,
               window_total AS total_amount,
               window_count AS deposit_count,
               ROW_NUMBER() OVER (
                   PARTITION BY account_id ORDER BY window_count DESC, txn_timestamp
               ) AS rn
        FROM windowed
        WHERE window_count >= 3
    )
    SELECT account_id, customer_id, evidence_txn_ids, total_amount, deposit_count
    FROM best_per_account
    WHERE rn = 1;

    INSERT INTO FINDINGS
        (FINDING_ID, SIGNAL_ID, SIGNAL_TYPE, SEVERITY, ACCOUNT_ID, CUSTOMER_ID,
         CUSTOMER_NAME, CREATED_AT, NARRATIVE, RECOMMENDED_ACTION, STATUS,
         EVIDENCE, CITATIONS, HISTORY, NOTES)
    SELECT
        'FIND-' || UPPER(SUBSTR(SHA2(c.account_id || CURRENT_TIMESTAMP()::STRING), 1, 8)),
        'SIG-STRUCT-' || c.account_id || '-' || TO_VARCHAR(CURRENT_TIMESTAMP(), 'YYYYMMDDHH24MISS'),
        'structuring', 'High', c.account_id, c.customer_id,
        cu.NAME,
        CURRENT_TIMESTAMP()::STRING,
        c.deposit_count || ' cash deposits totaling $' || TO_VARCHAR(c.total_amount, '999,999,999.00')
            || ' within a 5-day window, each individually below the $10,000 CTR threshold.',
        'Route to Compliance for structuring/smurfing review under AML-TM-2; consider a SAR filing if pattern is corroborated.',
        'Open',
        TO_VARIANT(c.evidence_txn_ids),
        PARSE_JSON('["AML-TM-2"]'),
        PARSE_JSON('[{"event":"created","at":"' || CURRENT_TIMESTAMP()::STRING || '","detail":"Finding generated by scheduled task DETECT_AND_FILE_STRUCTURING_TASK"}]'),
        PARSE_JSON('[]')
    FROM TMP_CANDIDATES c
    JOIN CUSTOMERS cu ON cu.CUSTOMER_ID = c.customer_id
    WHERE NOT EXISTS (
        SELECT 1 FROM FINDINGS f
        WHERE f.ACCOUNT_ID = c.account_id AND f.SIGNAL_TYPE = 'structuring'
    );

    new_findings_count := SQLROWCOUNT;
    RETURN 'Structuring detector ran. New findings filed: ' || new_findings_count;
END;
$$;

-- Schedule it: daily at 02:00 UTC (illustrative cadence for a demo -- a real
-- deployment would tune this to the actual transaction ingestion cadence).
CREATE OR REPLACE TASK DETECT_AND_FILE_STRUCTURING_TASK
    WAREHOUSE = COMPUTE_WH
    SCHEDULE = 'USING CRON 0 2 * * * UTC'
AS
    CALL DETECT_AND_FILE_STRUCTURING();

ALTER TASK DETECT_AND_FILE_STRUCTURING_TASK RESUME;

