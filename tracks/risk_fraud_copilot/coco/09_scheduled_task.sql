--
-- Confirmed live: CREATE TASK / RESUME / EXECUTE TASK all succeeded, and
-- INFORMATION_SCHEMA.TASK_HISTORY() shows a real SUCCEEDED run. Re-running
-- it against the same data correctly filed zero new findings (idempotent --
-- matched on ACCOUNT_ID + SIGNAL_TYPE), proving it's safe to run
-- unattended on a schedule without duplicating audit records.
